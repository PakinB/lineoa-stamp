-- รางวัลจริงของร้าน: ถึงดวงที่ 6, 8, 10 ได้ของตามลำดับ
-- ถ้าอยากเปลี่ยนตำแหน่งหรือปิดจุดไหน แก้ที่นี่ ไม่ต้องแตะโค้ด
INSERT INTO reward_checkpoints (slot_no, label) VALUES
  (6,  'โค้กฟรี 1 ขวด'),
  (8,  'เฉาก๋วยฟรี'),
  (10, 'หมาล่าฟรี 300 กรัม')
ON CONFLICT (slot_no) DO NOTHING;

-- ปกติ checkpoint ละ 1 ตัวเลือก แต่ตารางรองรับหลายตัวเลือกไว้
-- เผื่อวันไหนของหมด เจ้าของเพิ่มของทดแทนได้จากหน้าแอดมินโดยไม่ต้องแก้โค้ด (§2)
INSERT INTO reward_options (checkpoint_id, name, sort)
SELECT c.id, v.name, v.sort
  FROM reward_checkpoints c
  JOIN (VALUES
    (6,  'โค้กฟรี 1 ขวด',      1),
    (8,  'เฉาก๋วยฟรี',          1),
    (10, 'หมาล่าฟรี 300 กรัม',  1)
  ) AS v(slot, name, sort) ON v.slot = c.slot_no
ON CONFLICT DO NOTHING;

